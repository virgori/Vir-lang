"""
cost_model.py – Architecture-Aware Instruction Cost Model for Vir
==================================================================
Loads arch_config.json (generated by micro-prober + LLVM parser)
and provides cost queries for the optimizer and codegen.

Key features:
  - Per-opcode latency, throughput, micro-op count
  - Branch misprediction penalty
  - Memory hierarchy costs
  - Register spill cost estimation
  - Basic block and function cost estimation
  - Variant cost comparison for multi-versioning

Usage:
    from src.ir.cost_model import CostModel
    cm = CostModel("arm64")
    print(cm.latency(Opcode.Q_MUL))   # → 3
    print(cm.block_cost(instrs))       # → 42.5
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional, Sequence

from src.ir.instructions.q_ir import Opcode, QInstruction, QFunction, VReg


# ═══════════════════════════════════════════════════════════
# Data Structures
# ═══════════════════════════════════════════════════════════

@dataclass(frozen=True)
class InstrCostEntry:
    """Cost entry for a single Q-IR opcode mapped to native instruction."""
    opcode: Opcode
    mnemonic: str         # native instruction name (e.g. "ADD", "SDIV")
    latency: int          # cycles from input ready to output ready
    throughput: float     # instructions per cycle (reciprocal throughput)
    uops: int             # micro-ops consumed
    category: str         # "arith", "mul", "div", "load", "store", "branch", "cmp"
    sched_class: str = ""  # scheduling class hint (INT_ALU, INT_MUL, etc.)


@dataclass(frozen=True)
class BranchCostInfo:
    predict_hit: float
    predict_miss: float
    miss_penalty: float


@dataclass(frozen=True)
class MemoryCostInfo:
    l1_latency: float
    l2_latency: float
    l3_latency: float
    mem_latency: float
    store_latency: float


@dataclass(frozen=True)
class SpillCostInfo:
    spill_store: int
    spill_load: int
    total: int


@dataclass(frozen=True)
class CacheTopology:
    """Runtime cache topology from cpu_caps."""
    cache_line_size: int = 64
    l1d_size_kb: int = 64
    l1d_assoc: int = 8
    l1i_size_kb: int = 128
    l2_size_kb: int = 4096
    l2_assoc: int = 16
    l3_size_kb: int = 0
    l3_assoc: int = 0


@dataclass(frozen=True)
class TLBInfo:
    """TLB parameters for memory hierarchy model."""
    page_size: int = 16384
    l1_dtlb_entries: int = 256
    l1_itlb_entries: int = 192
    l2_tlb_entries: int = 4096
    huge_page_size: int = 33554432  # 32MB


@dataclass(frozen=True)
class PrefetchConfig:
    """Prefetch parameters for data locality optimization."""
    hw_prefetch_distance: int = 16      # cache lines
    sw_prefetch: bool = True
    prefetch_hint_size: int = 512       # bytes
    optimal_stride: int = 64            # bytes (1 cache line)


@dataclass(frozen=True)
class PackCostInfo:
    """Cost of packing/unpacking scalar data to/from SIMD registers.

    When vectorizing, GPR scalar values must be moved into vector
    registers (packing) and results extracted back (unpacking).
    This overhead can negate SIMD benefits for short sequences.
    """
    pack_latency: int = 3       # cycles to INS/DUP scalar → vector lane
    unpack_latency: int = 2     # cycles to UMOV/extract lane → scalar
    lanes_per_pack: int = 1     # how many lanes one pack op fills
    alignment_penalty: float = 1.5  # multiplier for unaligned access


