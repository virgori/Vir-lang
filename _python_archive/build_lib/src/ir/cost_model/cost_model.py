    def summary(self) -> str:
        """Human-readable summary of the cost model."""
        lines = [
            f"CostModel: {self.arch} ({self.cpu})",
            f"  Issue width: {self.issue_width}",
            f"  SIMD width: {self.max_simd_width} bytes ({self.max_simd_width * 8}-bit)",
            f"  Branch miss penalty: {self.branch.miss_penalty:.0f} cycles",
            f"  Memory: L1={self.memory.l1_latency:.0f}c L2={self.memory.l2_latency:.0f}c"
            f" L3={self.memory.l3_latency:.0f}c RAM={self.memory.mem_latency:.0f}c",
            f"  Cache: L1D={self.cache.l1d_size_kb}KB/{self.cache.l1d_assoc}-way"
            f" L2={self.cache.l2_size_kb}KB/{self.cache.l2_assoc}-way"
            f" line={self.cache.cache_line_size}B",
            f"  TLB: dTLB={self.tlb.l1_dtlb_entries} iTLB={self.tlb.l1_itlb_entries}"
            f" L2TLB={self.tlb.l2_tlb_entries} page={self.tlb.page_size}B",
            f"  Prefetch: HW={self.prefetch.hw_prefetch_distance} lines"
            f" hint={self.prefetch.prefetch_hint_size}B",
            f"  Pack/Unpack: pack={self.pack_cost.pack_latency}c"
            f" unpack={self.pack_cost.unpack_latency}c"
            f" align_penalty={self.pack_cost.alignment_penalty:.1f}×"
            f" min_vec_count={self.min_vectorize_count}",
            f"  Spill cost: {self.spill.total} cycles (store={self.spill.spill_store} + load={self.spill.spill_load})",
            "",
            "  Opcode costs (latency / IPC):",
        ]
        for opcode in sorted(self._costs, key=lambda o: o.name):
            e = self._costs[opcode]
            lines.append(f"    {opcode.name:20s} → {e.mnemonic:8s}  lat={e.latency:2d}  thr={e.throughput:5.2f}")
        return "\n".join(lines)
