class CostModel:
    """
    Architecture-aware cost model for Q-IR instructions.

    Loads cost data from arch_config.json files generated by the
    micro-prober and LLVM TableGen parser.
    """

    # Default config file locations (relative to project root)
    _CONFIG_PATHS = {
        "arm64":  "data/arch/arm64_config.json",
        "x86_64": "data/arch/x86_64_config.json",
        "rv64":   "data/arch/rv64_config.json",
    }

    def __init__(self, arch: str = "arm64", config_path: Optional[str] = None) -> None:
        self.arch = arch
        self._costs: dict[Opcode, InstrCostEntry] = {}
        self.branch = BranchCostInfo(1.0, 14.0, 13.0)
        self.memory = MemoryCostInfo(4.0, 12.0, 40.0, 200.0, 1.0)
        self.spill = SpillCostInfo(1, 4, 5)
        self.issue_width: int = 4
        self.cpu: str = "unknown"
        self.cache = CacheTopology()
        self.tlb = TLBInfo()
        self.prefetch = PrefetchConfig()
        self.pack_cost = PackCostInfo()
        self.max_simd_width: int = 16  # bytes (128-bit default)
        self.min_vectorize_count: int = 8  # minimum elements to justify SIMD
        # Per-opcode optimizer traits loaded from metadata
        self._traits: dict[str, dict] = {}  # opcode_name -> {pure, commutative, ...}

        # Locate config file
        if config_path:
            cfg_file = Path(config_path)
        else:
            # Try relative to this file (src/ir/cost_model/) → project root
            project_root = Path(__file__).resolve().parent.parent.parent.parent
            cfg_file = project_root / self._CONFIG_PATHS.get(arch, "")

        if cfg_file.exists():
            self._load_config(cfg_file)
        else:
            # Fall back to hardcoded defaults
            self._load_defaults()

        # Attempt to overlay opcode_metadata.json for refined heuristics
        self._try_load_opcode_metadata()

    def _load_config(self, path: Path) -> None:
        """Load cost model from arch_config.json."""
        with open(path) as f:
            data = json.load(f)

        self.cpu = data.get("cpu", "unknown")
        self.issue_width = data.get("issue_width", 4)

        # Build Q-IR → mnemonic mapping
        qir_map: dict[str, str] = data.get("qir_map", {})
        # Build mnemonic → cost lookup from instructions array
        mnemonic_costs: dict[str, dict] = {}
        for entry in data.get("instructions", []):
            mnemonic_costs[entry["mnemonic"]] = entry

        # Map each Q-IR opcode
        for opcode in Opcode:
            qir_name = opcode.name  # e.g. "Q_ADD"
            mnemonic = qir_map.get(qir_name, "NOP")
            cost_data = mnemonic_costs.get(mnemonic, {})

            self._costs[opcode] = InstrCostEntry(
                opcode=opcode,
                mnemonic=mnemonic,
                latency=cost_data.get("latency", 1),
                throughput=cost_data.get("throughput", 1.0),
                uops=cost_data.get("uops", 1),
                category=cost_data.get("category", "arith"),
            )

        # Load branch, memory, spill costs
        br = data.get("branch", {})
        if br:
            self.branch = BranchCostInfo(
                predict_hit=br.get("predict_hit", 1.0),
                predict_miss=br.get("predict_miss", 14.0),
                miss_penalty=br.get("miss_penalty", 13.0),
            )

        mem = data.get("memory", {})
        if mem:
            self.memory = MemoryCostInfo(
                l1_latency=mem.get("l1_latency", 4.0),
                l2_latency=mem.get("l2_latency", 12.0),
                l3_latency=mem.get("l3_latency", 40.0),
                mem_latency=mem.get("mem_latency", 200.0),
                store_latency=mem.get("store_latency", 1.0),
            )

        sp = data.get("spill", {})
        if sp:
            self.spill = SpillCostInfo(
                spill_store=sp.get("spill_store", 1),
                spill_load=sp.get("spill_load", 4),
                total=sp.get("total", 5),
            )

