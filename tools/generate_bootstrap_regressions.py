CASES: dict[str, tuple[str, str]] = {}


def case(name: str, expected: str | int, body: str) -> None:
    if name in CASES:
        raise ValueError(f"duplicate generated test: {name}")
    source = f"# GENERATED by tools/generate_bootstrap_regressions.py\n# EXPECT: {expected}\n{body.strip()}\n"
    CASES[name] = (f"{expected}\n", source)


def main_program(expr: str) -> str:
    return f"""
func main:
    print({expr});
    out 0;
end.
"""


