def generate() -> None:
    TEST_DIR.mkdir(parents=True, exist_ok=True)
    obsolete = TEST_DIR / "cg_global.vri"
    if obsolete.exists():
        obsolete.unlink()

    local_scope = TEST_DIR / "cg_local_scope.vri"
    local_scope.write_text(
        "# Globals are not in the Stage-1 subset; verify local reassignment instead.\n"
        "# EXPECT: 7\n"
        "func main:\n"
        "    let x = 0;\n"
        "    x = 7;\n"
        "    print(x);\n"
        "    out 0;\n"
        "end.\n",
        encoding="utf-8",
    )

    for name, (_, source) in sorted(CASES.items()):
        (TEST_DIR / name).write_text(source, encoding="utf-8")

    expected = dict(BASELINE_EXPECTED)
    expected.update({name: stdout.replace("\\n", "\n") for name, (stdout, _) in CASES.items()})
    if len(expected) != 100:
        raise AssertionError(f"expected exactly 100 tests, got {len(expected)}")
    missing = sorted(name for name in expected if not (TEST_DIR / name).is_file())
    if missing:
        raise FileNotFoundError(f"missing baseline tests: {missing}")

    manifest = {
        "schema": 1,
        "notes": {
            "supported": [
                "expression precedence",
                "recursion",
                "nested calls",
                "array-like memory via alloc/read/write",
                "string literals",
                "control flow",
                "i64 overflow",
                "parser and runtime edge cases",
            ],
            "unsupported_in_stage1": ["closures", "structs", "module globals"],
        },
        "tests": [
            {"file": name, "stdout": stdout, "exit": 0}
            for name, stdout in sorted(expected.items())
        ],
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"generated {len(CASES)} fixtures; manifest contains {len(expected)} tests")


if __name__ == "__main__":
    generate()
